// NODE: "Check test cases"  (Code node, mode: Run Once for Each Item)
// The quality gate. Reads Claude's answer and checks it like a QA lead before anything is
// posted to Jira: every criterion covered, no broken references, negative or boundary
// tests present, no duplicates, no empty steps.

const story = $('Build test request').item.json;
const response = $json;
const issues = [];

const text = (response.content ?? []).filter((b) => b.type === 'text').map((b) => b.text).join('');
if (response.error) issues.push(`The Claude request failed: ${JSON.stringify(response.error).slice(0, 300)}`);
if (response.stop_reason === 'refusal') issues.push('Claude declined this story (stop_reason: refusal).');
if (response.stop_reason === 'max_tokens') issues.push('The answer was cut off. Raise MAX_TOKENS in "Build test request".');

let result = null;
try {
  result = JSON.parse(text);
} catch (error) {
  if (!issues.length) issues.push('The answer was not valid JSON.');
}
result = result ?? {
  status: 'error', statusReason: issues.join(' '), sectionName: '', acceptanceCriteria: [], testCases: [],
  assumptions: [], clarifyingQuestions: [],
};

// Where each criterion came from: the document, Jira, or written by AI.
const originalSource = Object.fromEntries(story.acceptanceCriteria.map((ac) => [ac.id, ac.source]));
const label = { document: 'Document', jira: 'Jira', generated: 'Generated by AI' };
const criteria = result.acceptanceCriteria.map((ac) => ({
  ...ac,
  source: label[originalSource[ac.id]] ?? (ac.source === 'generated' ? 'Generated by AI' : 'Given'),
}));

const tests = result.testCases;
const ids = criteria.map((ac) => ac.id);
const covered = new Set(tests.flatMap((t) => t.covers));
const uncovered = ids.filter((id) => !covered.has(id));
const unknown = [...covered].filter((id) => !ids.includes(id));
const dropped = story.acceptanceCriteria.map((ac) => ac.id).filter((id) => !ids.includes(id));
const dupes = (values) => values.filter((v, i) => values.indexOf(v) !== i);
const types = tests.reduce((mix, t) => ({ ...mix, [t.type]: (mix[t.type] ?? 0) + 1 }), {});

if (result.status === 'ok') {
  if (!tests.length) issues.push('Status is ok but there are no test cases.');
  if (uncovered.length) issues.push(`Criteria without a test: ${uncovered.join(', ')}.`);
  if (dropped.length) issues.push(`Criteria missing from the answer: ${dropped.join(', ')}.`);
  if (unknown.length) issues.push(`Tests refer to unknown criteria: ${unknown.join(', ')}.`);
  // Tests that try something that must fail: invalid input, limits, forbidden roles, attacks.
  if (!types.Negative && !types.Boundary && !types.Permission && !types.Security) {
    issues.push('No negative, boundary, permission or security test.');
  }
  if (dupes(tests.map((t) => t.scenario.trim().toLowerCase())).length) issues.push('Duplicate test scenarios.');
  const empty = tests.filter((t) => !t.steps.length || !t.expectedResult.trim()).map((t) => t.id);
  if (empty.length) issues.push(`Tests without steps or an expected result: ${empty.join(', ')}.`);
} else if (result.status === 'needs_clarification' && !result.clarifyingQuestions.length) {
  issues.push('Clarification requested but no questions were asked.');
}

return {
  json: {
    ...story,
    anthropicRequest: undefined,
    sectionName: (story.shortName || result.sectionName || story.title).slice(0, 22),
    acceptanceCriteria: criteria,
    generatedCriteria: criteria.filter((ac) => ac.source === 'Generated by AI').length,
    testStatus: result.status,
    statusReason: result.statusReason,
    testCases: tests,
    assumptions: result.assumptions,
    clarifyingQuestions: result.clarifyingQuestions,
    quality: {
      passed: result.status === 'ok' && issues.length === 0,
      issues,
      coveragePct: ids.length ? Math.round(((ids.length - uncovered.length) / ids.length) * 100) : 0,
      types,
    },
    usage: response.usage ?? {},
    seconds: Math.round((Date.now() - story.startedAt) / 1000),
  },
};
