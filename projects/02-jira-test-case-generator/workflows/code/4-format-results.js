// NODE: "Format results"  (Code node, mode: Run Once for Each Item)
// Produces every output format from the checked test cases:
//   jiraComment  Jira wiki markup (table + full steps), posted on the story
//   html         results page shown after the web form
//   csv          spreadsheet / test-management import (Xray, Zephyr, TestRail all accept CSV)
//   record       the row saved to Postgres
//   apiResponse  JSON returned to API callers (and the evaluation script)

const r = $json;
const tests = r.testCases;
const q = r.quality;
const today = new Date().toISOString().slice(0, 10);
const testsFor = (acId) => tests.filter((t) => t.covers.includes(acId)).map((t) => t.id);

// ── Jira comment (wiki markup) ───────────────────────────────────────────────
// Characters that would break a wiki table or trigger macros are replaced.
const wiki = (value) => String(value ?? '').replace(/\|/g, '/').replace(/[{}]/g, '').replace(/\r?\n/g, ' ');
let jira;
if (r.status === 'ok') {
  jira = [
    `h3. AI-generated test cases (${tests.length})`,
    `_Generated by ${r.model} on ${today}. A QA engineer should review them before use._`,
    `*Quality check:* ${q.passed ? '(/) passed' : '(!) needs review'} · *Acceptance-criteria coverage:* ${q.coveragePct}% (${q.criteriaCount - q.uncovered.length}/${q.criteriaCount}) · *Automation candidates:* ${q.automationCandidates}`,
    ...(q.issues.length ? ['', ...q.issues.map((i) => `* (!) ${wiki(i)}`)] : []),
    '',
    'h4. Traceability',
    '||Criterion||Covered by||',
    ...r.acceptanceCriteria.map((ac) => `|${ac.id}: ${wiki(ac.text)}|${testsFor(ac.id).join(', ') || '(x) none'}|`),
    '',
    'h4. Test cases',
    '||ID||Title||Type||Priority||Covers||Automate||',
    ...tests.map((t) => `|${t.id}|${wiki(t.title)}|${t.type}|${t.priority}|${t.covers.join(', ')}|${t.automationCandidate ? 'Yes' : 'No'}|`),
    ...tests.flatMap((t) => [
      '',
      `h5. ${t.id} · ${wiki(t.title)}`,
      `*Preconditions:* ${wiki(t.preconditions)}`,
      `*Test data:* ${wiki(t.testData)}`,
      ...t.steps.map((step) => `# ${wiki(step)}`),
      `*Expected result:* ${wiki(t.expectedResult)}`,
    ]),
    ...(r.assumptions.length ? ['', 'h4. Assumptions', ...r.assumptions.map((a) => `* ${wiki(a)}`)] : []),
    ...(r.clarifyingQuestions.length ? ['', 'h4. Open questions for the product owner', ...r.clarifyingQuestions.map((x) => `* ${wiki(x)}`)] : []),
  ].join('\n');
} else {
  jira = [
    r.status === 'needs_clarification' ? 'h3. Test design needs clarification' : 'h3. No test cases generated',
    `_Checked by ${r.model} on ${today}._`,
    wiki(r.statusReason),
    ...(r.clarifyingQuestions.length ? ['', 'Please answer these questions in the story, then remove the label *ai-tests-need-info*:', ...r.clarifyingQuestions.map((x) => `* ${wiki(x)}`)] : []),
  ].join('\n');
}
// Jira comments are limited to 32,767 characters.
if (jira.length > 32000) jira = `${jira.slice(0, 31800)}\n\n_(Truncated: see the full set in the test library or the CSV export.)_`;

// ── CSV ──────────────────────────────────────────────────────────────────────
const cell = (value) => `"${String(value ?? '').replace(/"/g, '""')}"`;
const csv = [
  ['Issue key', 'Test ID', 'Title', 'Type', 'Priority', 'Covers', 'Preconditions', 'Test data', 'Steps', 'Expected result', 'Automation candidate'],
  ...tests.map((t) => [
    r.issueKey, t.id, t.title, t.type, t.priority, t.covers.join(' '), t.preconditions, t.testData,
    t.steps.map((step, i) => `${i + 1}. ${step}`).join('\n'), t.expectedResult, t.automationCandidate ? 'Yes' : 'No',
  ]),
].map((row) => row.map(cell).join(',')).join('\r\n');

// ── HTML results page (shown after the form) ─────────────────────────────────
const esc = (value) => String(value ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const badge = (label, tone) => `<span class="badge ${tone}">${esc(label)}</span>`;
const list = (items) => `<ul>${items.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>`;
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<style>
  body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:0;background:#f4f6fb;color:#1f2937}
  main{max-width:980px;margin:0 auto;padding:24px 16px 48px}
  h1{font-size:22px;margin:0 0 4px} h2{font-size:16px;margin:28px 0 10px} .muted{color:#6b7280;font-size:13px}
  .card{background:#fff;border:1px solid #e5e7eb;border-radius:10px;padding:16px;margin:10px 0}
  .badges{display:flex;flex-wrap:wrap;gap:6px;margin:12px 0}
  .badge{font-size:12px;padding:3px 9px;border-radius:999px;background:#eef2ff;color:#3730a3}
  .good{background:#dcfce7;color:#166534} .warn{background:#fef3c7;color:#92400e} .bad{background:#fee2e2;color:#991b1b}
  table{width:100%;border-collapse:collapse;font-size:13px} th,td{text-align:left;padding:7px 8px;border-bottom:1px solid #e5e7eb;vertical-align:top}
  th{background:#f9fafb;font-weight:600} .tc h3{font-size:15px;margin:0 0 6px} ol{margin:6px 0 6px 18px;padding:0} li{margin:2px 0}
  .label{font-weight:600;font-size:12px;color:#374151;text-transform:uppercase;letter-spacing:.03em}
</style></head><body><main>
<h1>${esc(r.issueKey ? `${r.issueKey} · ` : '')}${esc(r.summary || 'Test design')}</h1>
<div class="muted">Generated by ${esc(r.model)} on ${today} in ${(r.latencyMs / 1000).toFixed(1)} s${r.fromJira ? ' · posted to the Jira story' : ''}</div>
<div class="badges">
  ${badge(r.status === 'ok' ? `${tests.length} test cases` : r.status.replace('_', ' '), r.status === 'ok' ? 'good' : 'warn')}
  ${r.status === 'ok' ? badge(`Coverage ${q.coveragePct}%`, q.coveragePct === 100 ? 'good' : 'bad') : ''}
  ${badge(q.passed ? 'Quality check passed' : 'Needs review', q.passed ? 'good' : 'bad')}
  ${r.status === 'ok' ? badge(`${q.automationCandidates} automation candidates`, '') : ''}
  ${Object.entries(q.typeMix).map(([type, n]) => badge(`${n} ${type}`, '')).join('')}
</div>
${q.issues.length ? `<div class="card"><span class="label">Quality issues</span>${list(q.issues)}</div>` : ''}
${r.status !== 'ok' ? `<div class="card"><span class="label">Why</span><p>${esc(r.statusReason)}</p></div>` : ''}
${r.clarifyingQuestions.length ? `<div class="card"><span class="label">Questions for the product owner</span>${list(r.clarifyingQuestions)}</div>` : ''}
${r.acceptanceCriteria.length ? `<h2>Traceability</h2><div class="card"><table><tr><th>Criterion</th><th>Source</th><th>Covered by</th></tr>
${r.acceptanceCriteria.map((ac) => `<tr><td><b>${esc(ac.id)}</b> ${esc(ac.text)}</td><td>${esc(ac.source)}</td><td>${esc(testsFor(ac.id).join(', ') || 'none')}</td></tr>`).join('')}</table></div>` : ''}
${tests.length ? `<h2>Test cases</h2>${tests.map((t) => `<div class="card tc"><h3>${esc(t.id)} · ${esc(t.title)}</h3>
<div class="badges">${badge(t.type, '')}${badge(`${t.priority} priority`, t.priority === 'High' ? 'warn' : '')}${badge(`Covers ${t.covers.join(', ')}`, '')}${t.automationCandidate ? badge('Automate', 'good') : ''}</div>
<div><span class="label">Preconditions</span> ${esc(t.preconditions)}</div>
<div><span class="label">Test data</span> ${esc(t.testData)}</div>
<ol>${t.steps.map((step) => `<li>${esc(step)}</li>`).join('')}</ol>
<div><span class="label">Expected</span> ${esc(t.expectedResult)}</div></div>`).join('')}` : ''}
${r.assumptions.length ? `<h2>Assumptions</h2><div class="card">${list(r.assumptions)}</div>` : ''}
<p class="muted">AI-generated: review before use. Saved to the test library (Postgres).</p>
</main></body></html>`;

// ── Postgres record and API response ─────────────────────────────────────────
const record = {
  issueKey: r.issueKey || null,
  summary: r.summary,
  channel: r.channel,
  status: r.status,
  model: r.model,
  criteriaCount: q.criteriaCount,
  testCount: q.testCount,
  coveragePct: q.coveragePct,
  qualityPassed: q.passed,
  qualityIssues: q.issues,
  acceptanceCriteria: r.acceptanceCriteria,
  testCases: tests,
  inputTokens: r.usage.inputTokens,
  outputTokens: r.usage.outputTokens,
  latencyMs: r.latencyMs,
};

const apiResponse = {
  issueKey: r.issueKey,
  summary: r.summary,
  status: r.status,
  statusReason: r.statusReason,
  quality: q,
  acceptanceCriteria: r.acceptanceCriteria,
  testCases: tests,
  assumptions: r.assumptions,
  clarifyingQuestions: r.clarifyingQuestions,
  model: r.model,
  usage: r.usage,
  latencyMs: r.latencyMs,
  csv,
};

// Label that stops the scheduled scan from picking the story up again.
const doneLabel = r.status === 'ok' ? 'ai-tests-generated' : 'ai-tests-need-info';

return {
  json: {
    issueKey: r.issueKey,
    channel: r.channel,
    fromJira: r.fromJira,
    jiraLabels: [...new Set([...(r.labels ?? []), doneLabel])],
    jiraComment: jira,
    html,
    record,
    apiResponse,
  },
};
